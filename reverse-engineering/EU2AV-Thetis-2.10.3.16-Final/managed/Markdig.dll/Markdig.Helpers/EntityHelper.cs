	public static string? DecodeEntity(ReadOnlySpan<char> entity)
	{
		if (EntityMap.TryMatchExact(entity, out KeyValuePair<string, string> match))
		{
			return match.Value;
		}
		return null;
	}

	public static string DecodeEntity(int utf32)
	{
		if (utf32 == 0 || !UnicodeUtility.IsValidUnicodeScalar((uint)utf32))
		{
			return "\ufffd";
		}
		if (UnicodeUtility.IsBmpCodePoint((uint)utf32))
		{
			return char.ToString((char)utf32);
		}
		UnicodeUtility.GetUtf16SurrogatesFromSupplementaryPlaneScalar((uint)utf32, out var highSurrogateCodePoint, out var lowSurrogateCodePoint);
		return new string(new char[2] { highSurrogateCodePoint, lowSurrogateCodePoint });
	}

	internal static void DecodeEntity(int utf32, ref ValueStringBuilder sb)
	{
		if (utf32 == 0 || !UnicodeUtility.IsValidUnicodeScalar((uint)utf32))
		{
			sb.Append('\ufffd');
			return;
		}
		if (UnicodeUtility.IsBmpCodePoint((uint)utf32))
		{
			sb.Append((char)utf32);
			return;
		}
		UnicodeUtility.GetUtf16SurrogatesFromSupplementaryPlaneScalar((uint)utf32, out var highSurrogateCodePoint, out var lowSurrogateCodePoint);
		sb.Append(highSurrogateCodePoint);
		sb.Append(lowSurrogateCodePoint);
	}
