	public EmojiMapping(bool enableSmileys = true)
		: this(GetDefaultEmojiShortcodeToUnicode(), enableSmileys ? GetDefaultSmileyToEmojiShortcode() : new Dictionary<string, string>())
	{
	}

	public EmojiMapping(IDictionary<string, string> shortcodeToUnicode, IDictionary<string, string> smileyToShortcode)
	{
		if (shortcodeToUnicode == null)
		{
			ThrowHelper.ArgumentNullException("shortcodeToUnicode");
		}
		if (smileyToShortcode == null)
		{
			ThrowHelper.ArgumentNullException("smileyToShortcode");
		}
		int num = shortcodeToUnicode.Count + smileyToShortcode.Count;
		PrefixTree = new CompactPrefixTree<string>(num, num * 2, num * 2);
		HashSet<char> hashSet = new HashSet<char>();
		foreach (KeyValuePair<string, string> item in shortcodeToUnicode)
		{
			if (string.IsNullOrEmpty(item.Key) || string.IsNullOrEmpty(item.Value))
			{
				ThrowHelper.ArgumentException("The dictionaries cannot contain null or empty keys/values", "shortcodeToUnicode");
			}
			hashSet.Add(item.Key[0]);
			PrefixTree.Add(item);
		}
		foreach (KeyValuePair<string, string> item2 in smileyToShortcode)
		{
			if (string.IsNullOrEmpty(item2.Key) || string.IsNullOrEmpty(item2.Value))
			{
				ThrowHelper.ArgumentException("The dictionaries cannot contain null or empty keys/values", "smileyToShortcode");
			}
			if (!shortcodeToUnicode.TryGetValue(item2.Value, out string value))
			{
				ThrowHelper.ArgumentException($"Invalid smiley target: {item2.Value} is not present in the emoji shortcodes dictionary");
			}
			hashSet.Add(item2.Key[0]);
			if (!PrefixTree.TryAdd(item2.Key, value))
			{
				ThrowHelper.ArgumentException($"Smiley {item2.Key} is already present in the emoji mapping");
			}
		}
		OpeningCharacters = hashSet.ToArray();
	}
